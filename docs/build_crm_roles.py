# scenario block (violet, stands out)
def scenario(title, steps, result=None):
    cells = [[Paragraph(f"<b>СЦЕНАРИЙ · {sanitize(title)}</b>",
              st("sct", fontName="Arial-Bold", fontSize=10, leading=13, textColor=colors.white))]]
    body = []
    for i, s in enumerate(steps, 1):
        body.append(Paragraph(f"<b>{i}.</b> {sanitize(s)}", st(f"ss{i}", fontSize=9.5, leading=13.5, textColor=C_INK, leftIndent=2)))
    if result:
        body.append(Paragraph(f"<b>Итог:</b> {sanitize(result)}", st("sres", fontSize=9.5, leading=13.5, textColor=colors.HexColor('#059669'))))
    inner = Table([[b] for b in body], colWidths=[165*mm])
    inner.setStyle(TableStyle([("LEFTPADDING",(0,0),(-1,-1),0),("RIGHTPADDING",(0,0),(-1,-1),0),
                               ("TOPPADDING",(0,0),(-1,-1),1.5),("BOTTOMPADDING",(0,0),(-1,-1),1.5)]))
    head = Table(cells, colWidths=[171*mm]); head.setStyle(TableStyle([
        ("BACKGROUND",(0,0),(-1,-1),C_VIO),("LEFTPADDING",(0,0),(-1,-1),8),("RIGHTPADDING",(0,0),(-1,-1),8),
        ("TOPPADDING",(0,0),(-1,-1),4),("BOTTOMPADDING",(0,0),(-1,-1),4)]))
    box = Table([[inner]], colWidths=[171*mm]); box.setStyle(TableStyle([
        ("BACKGROUND",(0,0),(-1,-1),C_VIO_LT),("BOX",(0,0),(-1,-1),0.8,C_VIO),
        ("LEFTPADDING",(0,0),(-1,-1),8),("RIGHTPADDING",(0,0),(-1,-1),8),
        ("TOPPADDING",(0,0),(-1,-1),6),("BOTTOMPADDING",(0,0),(-1,-1),6)]))
    return [Spacer(1,4), head, box, Spacer(1,6)]

